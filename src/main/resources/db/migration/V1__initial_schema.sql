-- PDF: User  (table renamed app_user: "user" is reserved in PostgreSQL)
CREATE TABLE app_user (
    user_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(255) NOT NULL UNIQUE,
    username           VARCHAR(100) NOT NULL UNIQUE,
    name_first         VARCHAR(100),
    name_last          VARCHAR(100),
    age                INT,
    preference_id      BIGINT,
    gender             VARCHAR(20),
    pass               VARCHAR(100) NOT NULL,          -- BCrypt hash
    -- feature-required additions:
    phone              VARCHAR(30) UNIQUE,
    bio                VARCHAR(500),
    profile_image_path VARCHAR(255),
    two_factor_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    role               VARCHAR(20) NOT NULL DEFAULT 'USER',
    account_status     VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    warning_count      INT NOT NULL DEFAULT 0,
    created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- PDF: User_preference
CREATE TABLE user_preference (
    user_id         BIGINT PRIMARY KEY REFERENCES app_user(user_id),
    veg_noveg       BOOLEAN,
    calory          INT,
    protin          INT,
    pref_recipe_id  VARCHAR(255),
    uploaded_recipe VARCHAR(255)
);

-- PDF: Recipe (+ image_path for photo alongside recipe_video)
CREATE TABLE recipe (
    recipe_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_name       VARCHAR(255) NOT NULL,
    ingredient        TEXT,
    recipe_method     TEXT,
    recipe_video      VARCHAR(255),
    image_path        VARCHAR(255),
    recipe_creator_id BIGINT NOT NULL REFERENCES app_user(user_id),
    views             BIGINT NOT NULL DEFAULT 0,
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- PDF: Recipe_category
CREATE TABLE recipe_category (
    recipe_id     BIGINT PRIMARY KEY REFERENCES recipe(recipe_id),
    veg_nonveg    BOOLEAN,
    cooking_time  INT,
    calory        INT,
    protin        INT,
    preference_id BIGINT
);

-- PDF: Recipe_Rating
CREATE TABLE recipe_rating (
    rating_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT NOT NULL REFERENCES recipe(recipe_id),
    rate_1     INT DEFAULT 0,
    rate_2     INT DEFAULT 0,
    rate_3     INT DEFAULT 0,
    rate_4     INT DEFAULT 0,
    rate_5     INT DEFAULT 0,
    comments   TEXT,
    user_id    BIGINT REFERENCES app_user(user_id)
);

-- Remember-me (Spring Security JDBC persistent tokens)
CREATE TABLE persistent_logins (
    username  VARCHAR(64) NOT NULL,
    series    VARCHAR(64) PRIMARY KEY,
    token     VARCHAR(64) NOT NULL,
    last_used TIMESTAMP NOT NULL
);

-- 2FA + password-reset OTPs
CREATE TABLE email_otp (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user(user_id),
    purpose    VARCHAR(30) NOT NULL,
    code_hash  VARCHAR(100) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    consumed   BOOLEAN NOT NULL DEFAULT FALSE,
    attempts   INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Follow / subscription
CREATE TABLE subscription (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriber_id BIGINT NOT NULL REFERENCES app_user(user_id),
    creator_id    BIGINT NOT NULL REFERENCES app_user(user_id),
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (subscriber_id, creator_id)
);

-- Moderation warnings (3-strike ban)
CREATE TABLE warning (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user(user_id),
    reason     VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Direct messages (1:1 chat)
CREATE TABLE chat_message (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id   BIGINT NOT NULL REFERENCES app_user(user_id),
    recipient_id BIGINT NOT NULL REFERENCES app_user(user_id),
    body        TEXT NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
